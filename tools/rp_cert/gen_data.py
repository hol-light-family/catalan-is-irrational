import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from data import *
from fractions import Fraction as F
def hr(q):
    q = F(q)
    if q.denominator == 1:
        return ('&%d' % q.numerator) if q >= 0 else ('--(&%d)' % -q.numerator)
    return ('&%d / &%d' % (q.numerator, q.denominator)) if q >= 0 else ('--(&%d / &%d)' % (-q.numerator, q.denominator))
def hlist(l): return '[' + '; '.join(hr(a) for a in l) + ']'
def htail(tail):
    items = []
    for (c, z) in tail:
        if c[1] == 0 and z[1] == 0:
            items.append('(Cx(%s), Cx(%s))' % (hr(c[0]), hr(z[0])))
        else:
            items.append('(complex(%s, %s), complex(%s, %s))' % (hr(c[0]), hr(c[1]), hr(z[0]), hr(z[1])))
    return '[' + ';\n    '.join(items) + ']' if items else '[]:(complex#complex)list'
out = ['(* generated by tools/rp_cert/gen_data.py: trial data of Section 7.1 *)',
       'needs "src/catalan_rp_cert_base.ml";;', '']
for case in (1, 2):
    d = CASES[case]
    out.append('let rp_cert_c%d_kappa = `%s`;;' % (case, hr(d['kappa'])))
    out.append('let rp_cert_c%d_lam = `%s`;;' % (case, hr(d['lam'])))
    out.append('let rp_cert_c%d_lp = `%s:real list`;;' % (case, hlist(d['p'][0])))
    out.append('let rp_cert_c%d_tp = `%s`;;' % (case, htail(d['p'][1])))
    out.append('let rp_cert_c%d_lv = `%s:real list`;;' % (case, hlist(d['v'][0])))
    out.append('let rp_cert_c%d_tv = `%s`;;' % (case, htail(d['v'][1])))
    out.append('')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../src/catalan_rp_cert_data.ml'), 'w').write('\n'.join(out) + '\n')
