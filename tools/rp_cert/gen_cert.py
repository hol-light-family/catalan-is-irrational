from fractions import Fraction as F
import numpy as np
from apoly import mobius, var, pev
import num
D = os.path.dirname(os.path.abspath(__file__)) + '/'
def load(name):
    L = open(D + 'dump_%s.txt' % name).read().split('\n')
    A = [F(t) for t in L[0].split()]
    Q = [F(t) for t in L[1].split()]
    s = F(L[2])
    return A, Q, s
def roots_in(A, lo, hi):
    r = np.roots([float(a) for a in reversed(A)])
    return sorted(z.real for z in r if abs(z.imag) < 1e-7 and lo < z.real < hi)
def short(x, gap):
    dig = 2
    while 10**-dig > gap / 4: dig += 1
    return F(round(x * 10**dig), 10**dig)
def refine_root(A, a, b):
    # exact bisection on rationals, sign change between a and b
    fa = pev(A, a)
    for _ in range(400):
        m = (a + b) / 2
        fm = pev(A, m)
        if fm == 0: return m
        if (fm > 0) == (fa > 0): a, fa = m, fm
        else: b = m
        if b - a < F(1, 10**20): break
    return (a + b) / 2
def cert(name, intervals, fval):
    A, Q, s = load(name)
    out = []
    for (lo, hi) in intervals:
        rr = roots_in(A, float(lo), float(hi))
        pts = [lo]
        for i in range(len(rr) - 1):
            pts.append(short((rr[i] + rr[i + 1]) / 2, rr[i + 1] - rr[i]))
        pts.append(hi)
        pieces = []
        for i in range(len(pts) - 1):
            b, c = pts[i], pts[i + 1]
            v = var(mobius(A, b, c))
            inside = [z for z in rr if b < z < c]
            assert v <= 1 and v == len(inside), (name, b, c, v, inside)
            if v == 1:
                z = inside[0]
                # bracket [m, m+w] with sign change, m multiple of 1e-12
                assert (pev(A, b) > 0) != (pev(A, c) > 0), (name, b, c)
                r = refine_root(A, b, c)
                ka = sum(j*abs(x) for j, x in enumerate(A)); kq = sum(j*abs(x) for j, x in enumerate(Q))
                for e in (12, 13, 14, 15, 16, 17, 18):
                    Wl = F(1, 10**e)
                    m0 = F(int(r * 10**e), 10**e)
                    m = None
                    for k in (0, -1, 1, -2, 2, -3, 3):
                        mm = m0 + k * Wl
                        a1, a2 = pev(A, mm), pev(A, mm + Wl)
                        if a1 != 0 and a2 != 0 and (a1 > 0) != (a2 > 0): m = mm; break
                    assert m is not None
                    qm = abs(pev(Q, m))
                    if kq * Wl <= qm / 2 and ka * Wl * Wl / (s * (qm / 2)) <= F(1, 10**10): break
                else:
                    assert False, 'no bracket width'
                W = Wl
                pieces.append((b, c, (m, W)))
            else:
                pieces.append((b, c, None))
            for cc in (b, c):
                if lo < cc < hi: assert pev(A, cc) != 0
        # classify maxima: derivative sign just left of bracket: sign(A)*sign(Q) > 0
        maxes = []
        for (b, c, br) in pieces:
            if br is None: continue
            m, w = br
            sq = 1 if pev(Q, m) > 0 else -1
            if (pev(A, m) > 0) == (sq > 0): maxes.append(m)
        out.append((lo, hi, pieces, maxes))
    vals = {m: fval(float(m)) for (_, _, _, mx) in out for m in mx}
    return out, vals
def ocaml(name, data, vals, extra_pts=()):
    def r(q): return '"%s"' % (str(q))
    lines = ['let rp_cert_cert_%s = [' % name]
    for (lo, hi, pieces, maxes) in data:
        ps = []
        for (b, c, br) in pieces:
            if br is None: ps.append('(%s, %s, None)' % (r(b), r(c)))
            else: ps.append('(%s, %s, Some(%s, %s))' % (r(b), r(c), r(br[0]), r(br[1])))
        lines.append('  (%s, %s, [%s],\n   [%s]);' % (r(lo), r(hi), ';\n    '.join(ps), '; '.join(r(m) for m in maxes)))
    lines.append('];;')
    return '\n'.join(lines)
