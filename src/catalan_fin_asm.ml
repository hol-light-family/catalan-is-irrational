(* The final numerical step *)
let FIN_ASM_NUMERIC = prove
 (`forall N x S d f2 g s.
     1 <= N /\ ~(x = &0) /\ d = &1 / &1000 /\
     --S <= log(abs x) /\
     S <= (&505 / &4608 * &(48 * N) pow 2 + f2) * log(&2) + g + &N * s /\
     f2 <= d * &N pow 2 /\ g <= d * &N pow 2 /\ s <= (&8609 / &2 + d) * &N
     ==> --(&229084 / &100000) < cat_nlog N x`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[cat_nlog] THEN
  MP_TAC FIN_LOG2_UB THEN
  SUBGOAL_THEN `&0 < log(&2)` ASSUME_TAC THENL
   [MATCH_MP_TAC LOG_POS_LT THEN REAL_ARITH_TAC; ALL_TAC] THEN
  SUBGOAL_THEN `&1 <= &N` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[REAL_OF_NUM_LE]; ALL_TAC] THEN
  ABBREV_TAC `L2 = log(&2)` THEN ABBREV_TAC `n2 = &N pow 2` THEN
  SUBGOAL_THEN `&1 <= n2` ASSUME_TAC THENL
   [EXPAND_TAC "n2" THEN MATCH_MP_TAC REAL_POW_LE_1 THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN
  SUBGOAL_THEN `&(48 * N) pow 2 = &2304 * n2` SUBST_ALL_TAC THENL
   [EXPAND_TAC "n2" THEN REWRITE_TAC[GSYM REAL_OF_NUM_MUL] THEN REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `&N * s <= (&8609 / &2 + d) * n2` ASSUME_TAC THENL
   [EXPAND_TAC "n2" THEN REWRITE_TAC[REAL_POW_2] THEN
    SUBGOAL_THEN `(&8609 / &2 + d) * &N * &N = &N * ((&8609 / &2 + d) * &N)`
    SUBST1_TAC THENL [CONV_TAC REAL_RING; ALL_TAC] THEN
    MATCH_MP_TAC REAL_LE_LMUL THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `(&505 / &4608 * &2304 * n2 + f2) * L2 <= ((&505 / &2 + d) * n2) * L2`
  ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REAL_ARITH_TAC; ALL_TAC] THEN
  SUBGOAL_THEN `S <= ((&505 / &2 + d) * L2 + &8609 / &2 + &2 * d) * n2` ASSUME_TAC THENL
   [MATCH_MP_TAC REAL_LE_TRANS THEN
    EXISTS_TAC `((&505 / &2 + d) * n2) * L2 + d * n2 + (&8609 / &2 + d) * (n2:real)` THEN
    CONJ_TAC THENL [ASM_REAL_ARITH_TAC; REAL_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `--(((&505 / &2 + d) * L2 + &8609 / &2 + &2 * d) / &2304) <= (log(abs x) / (&2304 * n2):real)`
  MP_TAC THENL
   [SIMP_TAC[REAL_LE_RDIV_EQ; REAL_ARITH `&1 <= n ==> &0 < &2304 * n`;
             ASSUME `&1 <= n2`] THEN
    MATCH_MP_TAC REAL_LE_TRANS THEN EXISTS_TAC `--(S:real)` THEN
    CONJ_TAC THENL [ALL_TAC; ASM_REWRITE_TAC[]] THEN
    SUBGOAL_THEN `--(((&505 / &2 + d) * L2 + &8609 / &2 + &2 * d) / &2304) * (&2304 * n2) =
                  --(((&505 / &2 + d) * L2 + &8609 / &2 + &2 * d) * (n2:real))`
    SUBST1_TAC THENL [CONV_TAC REAL_FIELD; ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  ASM_REWRITE_TAC[] THEN REAL_ARITH_TAC);;

let FIN_ASM_GROWTH2 = prove
 (`forall N W lb L A.
      1 <= N /\ &1 <= W /\ &0 <= lb /\ &0 <= L /\ A = &240 * (lb + &1) + &66
      ==> W * (&240 * &N * (lb + L)) + (&65 * &N + &1) * L <= &N * (W * A * (&1 + L))`,
  REPEAT STRIP_TAC THEN ASM_REWRITE_TAC[] THEN
  SUBGOAL_THEN `&1 <= &N` ASSUME_TAC THENL [ASM_REWRITE_TAC[REAL_OF_NUM_LE]; ALL_TAC] THEN
  SUBGOAL_THEN `&0 <= &N * W * &240 * (lb * L + &1) /\
                &0 <= &N * (W - &1) * &66 * (&1 + L) /\
                &0 <= (&N - &1) * L`
  STRIP_ASSUME_TAC THENL
   [REPEAT CONJ_TAC THEN REPEAT(MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC) THEN
    ASM_SIMP_TAC[REAL_LE_MUL; REAL_LE_ADD; REAL_POS] THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
