  CONV_TAC(ONCE_DEPTH_CONV NUM_FACT_CONV) THEN CONV_TAC NUM_REDUCE_CONV THEN
  CONV_TAC REAL_RAT_REDUCE_CONV THEN
  REWRITE_TAC[REAL_ABS_NUM] THEN
