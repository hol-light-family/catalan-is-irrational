  SUBGOAL_THEN `&2 <= exp(&693149 / &1000000)` MP_TAC THENL
   [POP_ASSUM MP_TAC THEN REAL_ARITH_TAC; ALL_TAC] THEN
  DISCH_TAC THEN
  MP_TAC(SPECL [`&2`; `exp(&693149 / &1000000)`] LOG_MONO_LE_IMP) THEN
  ASM_REWRITE_TAC[LOG_EXP] THEN REAL_ARITH_TAC);;


let FIN_GROWTH = prove
 (`forall A d. &0 <= A /\ &0 < d
         ==> exists N0. forall N. N0 <= N
                  ==> (&2 * sqrt(&65 * &N) + &1) * A * (&1 + log(&65 * &N)) <= d * &N`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `tt = &780 * A / d + &1` THEN
  SUBGOAL_THEN `&1 <= tt /\ &780 * A < d * tt` STRIP_ASSUME_TAC THENL
   [EXPAND_TAC "tt" THEN CONJ_TAC THENL
     [MATCH_MP_TAC(REAL_ARITH `&0 <= x ==> &1 <= x + &1`) THEN
      ASM_SIMP_TAC[REAL_LE_MUL; REAL_LE_DIV; REAL_POS; REAL_LT_IMP_LE];
      ASM_SIMP_TAC[REAL_FIELD `&0 < d ==> d * (&780 * A / d + &1) = &780 * A + d`] THEN
      ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  MP_TAC(SPEC `(tt:real) pow 4` REAL_ARCH_SIMPLE) THEN
  DISCH_THEN(X_CHOOSE_TAC `M:num`) THEN EXISTS_TAC `M + 1` THEN
  X_GEN_TAC `N:num` THEN DISCH_TAC THEN
  SUBGOAL_THEN `tt pow 4 <= &65 * &N /\ &1 <= &N` STRIP_ASSUME_TAC THENL
