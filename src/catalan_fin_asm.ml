     [MATCH_MP_TAC REAL_LE_TRANS THEN EXISTS_TAC `&M` THEN ASM_REWRITE_TAC[] THEN
      REWRITE_TAC[REAL_OF_NUM_MUL; REAL_OF_NUM_LE] THEN ASM_ARITH_TAC;
      REWRITE_TAC[REAL_OF_NUM_LE] THEN ASM_ARITH_TAC];
