let FIN_ASM_SMALLCARD = prove
 (`forall X. FINITE {p | p * p <= X} /\
       &(CARD {p | p * p <= X}) <= sqrt(&X) + &1`,
  GEN_TAC THEN
  SUBGOAL_THEN `exists s. s * s <= X /\ forall p. p * p <= X ==> p <= s:num` STRIP_ASSUME_TAC THENL
   [SUBGOAL_THEN `exists s. ~((s + 1) * (s + 1) <= X:num)` MP_TAC THENL
     [EXISTS_TAC `X:num` THEN REWRITE_TAC[NOT_LE] THEN
      MATCH_MP_TAC(ARITH_RULE `X + 1 <= y ==> X < y:num`) THEN
      MATCH_MP_TAC(ARITH_RULE `1 * a <= a * a ==> a <= a * a:num`) THEN
      REWRITE_TAC[LE_MULT_RCANCEL] THEN ARITH_TAC;
      GEN_REWRITE_TAC LAND_CONV [num_WOP]] THEN
    DISCH_THEN(X_CHOOSE_THEN `s:num` STRIP_ASSUME_TAC) THEN
    EXISTS_TAC `s:num` THEN CONJ_TAC THENL
     [ASM_CASES_TAC `s = 0` THEN ASM_REWRITE_TAC[MULT_CLAUSES; LE_0] THEN
      FIRST_X_ASSUM(MP_TAC o SPEC `s - 1`) THEN
      ASM_SIMP_TAC[ARITH_RULE `~(s = 0) ==> s - 1 < s /\ s - 1 + 1 = s`];
      X_GEN_TAC `p:num` THEN DISCH_TAC THEN REWRITE_TAC[GSYM NOT_LT] THEN
      DISCH_TAC THEN UNDISCH_TAC `~((s + 1) * (s + 1) <= X)` THEN
      REWRITE_TAC[] THEN MATCH_MP_TAC LE_TRANS THEN
      EXISTS_TAC `p * p:num` THEN ASM_REWRITE_TAC[] THEN
      MATCH_MP_TAC LE_MULT2 THEN ASM_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `{p | p * p <= X} SUBSET 0..s` ASSUME_TAC THENL
   [REWRITE_TAC[SUBSET; IN_ELIM_THM; IN_NUMSEG] THEN ASM_MESON_TAC[LE_0];
    ALL_TAC] THEN
  CONJ_TAC THENL [ASM_MESON_TAC[FINITE_SUBSET; FINITE_NUMSEG]; ALL_TAC] THEN
  MATCH_MP_TAC REAL_LE_TRANS THEN EXISTS_TAC `&(CARD(0..s))` THEN CONJ_TAC THENL
   [REWRITE_TAC[REAL_OF_NUM_LE] THEN MATCH_MP_TAC CARD_SUBSET THEN
    ASM_REWRITE_TAC[FINITE_NUMSEG];
    REWRITE_TAC[CARD_NUMSEG; SUB_0; GSYM REAL_OF_NUM_ADD] THEN
    MATCH_MP_TAC(REAL_ARITH `x <= y ==> x + &1 <= y + &1`) THEN
    MATCH_MP_TAC REAL_LE_RSQRT THEN
    ASM_REWRITE_TAC[REAL_POW_2; REAL_OF_NUM_MUL; REAL_OF_NUM_LE]]);;

(* Termwise bound for the prime sum *)
let FIN_ASM_SUM = prove
 (`forall N b f K. 1 <= N /\ 1 <= b /\
    (forall p. p <= 65 * N ==> &(fin_loss N p) <= &N * fin_dfun(&p / &N)) /\
    (forall p. prime p /\ p <= 65 * N
         ==> &0 <= K p /\
             (p = 2 ==> K p = &505 / &4608 * &(48 * N) pow 2 + max (f N) (&0)) /\
             (~(p = 2) /\ p * p <= 260 * N
              ==> K p = &240 * &N * (&(fin_flog p b) + &(fin_flog p (65 * N)))) /\
             (~(p = 2) /\ ~(p * p <= 260 * N) ==> K p = &(fin_loss N p)))
    ==> sum {p | prime p /\ p <= 65 * N} (\p. (abs(K p) + &1) * log(&p))
        <= (&505 / &4608 * &(48 * N) pow 2 + max (f N) (&0)) * log(&2) +
           (&2 * sqrt(&65 * &N) + &1) * (&240 * &N * (log(&b) + log(&65 * &N))) +
           &N * sum {p | prime p /\ p <= 65 * N} (\p. fin_dfun(&p / &N) * log(&p)) +
           (&65 * &N + &1) * log(&65 * &N)`,
  REPEAT STRIP_TAC THEN
  ABBREV_TAC `P = {p | prime p /\ p <= 65 * N}` THEN
  SUBGOAL_THEN `FINITE(P:num->bool)` ASSUME_TAC THENL
   [EXPAND_TAC "P" THEN MATCH_MP_TAC FINITE_SUBSET THEN
    EXISTS_TAC `0..65 * N` THEN REWRITE_TAC[FINITE_NUMSEG; SUBSET; IN_NUMSEG; IN_ELIM_THM] THEN
    ARITH_TAC; ALL_TAC] THEN
  ABBREV_TAC `L = log(&65 * &N)` THEN
  ABBREV_TAC `X = &240 * &N * (log(&b) + L)` THEN
  ABBREV_TAC `K2 = &505 / &4608 * &(48 * N) pow 2 + max (f N) (&0)` THEN
  SUBGOAL_THEN `&0 <= log(&b) /\ &0 <= L /\ &0 <= X /\ &0 <= K2` STRIP_ASSUME_TAC THENL
   [MATCH_MP_TAC(TAUT `a /\ b /\ (a /\ b ==> c) /\ d ==> a /\ b /\ c /\ d`) THEN
    REPEAT CONJ_TAC THENL
     [MATCH_MP_TAC LOG_POS THEN ASM_REWRITE_TAC[REAL_OF_NUM_LE];
      EXPAND_TAC "L" THEN MATCH_MP_TAC LOG_POS THEN
      REWRITE_TAC[REAL_OF_NUM_MUL; REAL_OF_NUM_LE] THEN ASM_ARITH_TAC;
      STRIP_TAC THEN EXPAND_TAC "X" THEN MATCH_MP_TAC REAL_LE_MUL THEN
      REWRITE_TAC[REAL_POS] THEN MATCH_MP_TAC REAL_LE_MUL THEN
      REWRITE_TAC[REAL_POS] THEN ASM_REAL_ARITH_TAC;
      EXPAND_TAC "K2" THEN MATCH_MP_TAC REAL_LE_ADD THEN CONJ_TAC THENL
       [MATCH_MP_TAC REAL_LE_MUL THEN CONJ_TAC THENL
         [CONV_TAC REAL_RAT_REDUCE_CONV; SIMP_TAC[REAL_POW_LE; REAL_POS]];
        REAL_ARITH_TAC]];
    ALL_TAC] THEN
  MATCH_MP_TAC REAL_LE_TRANS THEN
  EXISTS_TAC `sum P (\p. (if p = 2 then K2 * log(&2) else &0) +
                         (if p * p <= 260 * N then X else &0) +
                         &N * (fin_dfun(&p / &N) * log(&p)) + L)` THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC SUM_LE THEN ASM_REWRITE_TAC[] THEN
    X_GEN_TAC `p:num` THEN EXPAND_TAC "P" THEN REWRITE_TAC[IN_ELIM_THM] THEN
    STRIP_TAC THEN
    FIRST_X_ASSUM(MP_TAC o SPEC `p:num`) THEN ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
    SUBGOAL_THEN `&2 <= &p /\ &p <= &65 * &N` STRIP_ASSUME_TAC THENL
     [FIRST_ASSUM(MP_TAC o MATCH_MP PRIME_GE_2) THEN
      UNDISCH_TAC `p <= 65 * N` THEN
      REWRITE_TAC[REAL_OF_NUM_MUL; REAL_OF_NUM_LE] THEN ARITH_TAC; ALL_TAC] THEN
    SUBGOAL_THEN `&0 <= log(&p) /\ log(&p) <= L` STRIP_ASSUME_TAC THENL
     [CONJ_TAC THENL
       [MATCH_MP_TAC LOG_POS THEN ASM_REAL_ARITH_TAC;
        EXPAND_TAC "L" THEN MATCH_MP_TAC LOG_MONO_LE_IMP THEN ASM_REAL_ARITH_TAC];
      ALL_TAC] THEN
    SUBGOAL_THEN `&0 <= &N * (fin_dfun(&p / &N) * log(&p))` ASSUME_TAC THENL
     [MATCH_MP_TAC REAL_LE_MUL THEN REWRITE_TAC[REAL_POS] THEN
      MATCH_MP_TAC REAL_LE_MUL THEN ASM_REWRITE_TAC[FIN_PNT_DFUN_POS];
      ALL_TAC] THEN
    ASM_SIMP_TAC[REAL_ARITH `&0 <= k ==> abs k = k`] THEN
    REWRITE_TAC[REAL_ADD_RDISTRIB; REAL_MUL_LID] THEN
    MATCH_MP_TAC(REAL_ARITH `a <= x + y + z /\ l <= L ==> a + l <= x + y + z + L`) THEN
    ASM_REWRITE_TAC[] THEN
    ASM_CASES_TAC `p = 2` THENL
     [UNDISCH_THEN `p = 2` SUBST_ALL_TAC THEN ASM_SIMP_TAC[] THEN
      COND_CASES_TAC THEN ASM_REAL_ARITH_TAC;
      ALL_TAC] THEN
    ASM_REWRITE_TAC[REAL_ADD_LID] THEN
    COND_CASES_TAC THENL
     [ASM_SIMP_TAC[] THEN
      MATCH_MP_TAC(REAL_ARITH `a <= x /\ &0 <= y ==> a <= x + y`) THEN
      ASM_REWRITE_TAC[] THEN EXPAND_TAC "X" THEN
      REWRITE_TAC[GSYM REAL_MUL_ASSOC] THEN
      MATCH_MP_TAC REAL_LE_LMUL THEN REWRITE_TAC[REAL_POS] THEN
      MATCH_MP_TAC REAL_LE_LMUL THEN REWRITE_TAC[REAL_POS] THEN
      REWRITE_TAC[REAL_ADD_RDISTRIB] THEN MATCH_MP_TAC REAL_LE_ADD2 THEN
      CONJ_TAC THEN TRY(EXPAND_TAC "L") THEN REWRITE_TAC[REAL_OF_NUM_MUL] THEN
      MATCH_MP_TAC FIN_BDRY_FLOG_LOG THEN
      REWRITE_TAC[ARITH_RULE `1 <= 65 * N <=> 1 <= N`] THEN
      ASM_SIMP_TAC[PRIME_GE_2];
      ASM_SIMP_TAC[REAL_ADD_LID] THEN
      REWRITE_TAC[REAL_MUL_ASSOC] THEN MATCH_MP_TAC REAL_LE_RMUL THEN
      ASM_SIMP_TAC[]];
    ALL_TAC] THEN
  ASM_SIMP_TAC[SUM_ADD; FINITE_RESTRICT] THEN
  REWRITE_TAC[GSYM SUM_RESTRICT_SET] THEN
  ASM_SIMP_TAC[SUM_CONST; FINITE_RESTRICT; SUM_LMUL] THEN
  SUBGOAL_THEN `{p | p IN P /\ p = 2} = {2}` SUBST1_TAC THENL
   [EXPAND_TAC "P" THEN REWRITE_TAC[EXTENSION; IN_ELIM_THM; IN_SING] THEN
    GEN_TAC THEN EQ_TAC THEN SIMP_TAC[PRIME_2] THEN
    DISCH_THEN SUBST1_TAC THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  REWRITE_TAC[CARD_SING; REAL_MUL_LID] THEN
  MATCH_MP_TAC(REAL_ARITH `a <= a' /\ b <= b' ==> k + a + s + b <= k + a' + s + b'`) THEN
  CONJ_TAC THENL
   [MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC REAL_LE_TRANS THEN
    EXISTS_TAC `&(CARD {p | p * p <= 260 * N})` THEN CONJ_TAC THENL
     [REWRITE_TAC[REAL_OF_NUM_LE] THEN MATCH_MP_TAC CARD_SUBSET THEN
      REWRITE_TAC[FIN_ASM_SMALLCARD] THEN SET_TAC[];
      MP_TAC(SPEC `260 * N` FIN_ASM_SMALLCARD) THEN
      REWRITE_TAC[GSYM REAL_OF_NUM_MUL] THEN
      SUBGOAL_THEN `sqrt(&260 * &N) = &2 * sqrt(&65 * &N)` SUBST1_TAC THENL
       [REWRITE_TAC[SQRT_MUL; REAL_MUL_ASSOC] THEN AP_THM_TAC THEN AP_TERM_TAC THEN
        MATCH_MP_TAC SQRT_UNIQUE THEN
        SIMP_TAC[REAL_LE_MUL; SQRT_POS_LE; REAL_POS; REAL_POW_MUL; SQRT_POW_2] THEN
        REAL_ARITH_TAC;
        SIMP_TAC[]]];
    MATCH_MP_TAC REAL_LE_RMUL THEN ASM_REWRITE_TAC[] THEN
    MATCH_MP_TAC REAL_LE_TRANS THEN EXISTS_TAC `&(CARD(0..65 * N))` THEN
    CONJ_TAC THENL
     [REWRITE_TAC[REAL_OF_NUM_LE] THEN MATCH_MP_TAC CARD_SUBSET THEN
      REWRITE_TAC[FINITE_NUMSEG] THEN EXPAND_TAC "P" THEN
      REWRITE_TAC[SUBSET; IN_ELIM_THM; IN_NUMSEG] THEN ARITH_TAC;
      REWRITE_TAC[CARD_NUMSEG; SUB_0; GSYM REAL_OF_NUM_ADD; GSYM REAL_OF_NUM_MUL] THEN
      REAL_ARITH_TAC]]);;

