     [REWRITE_TAC[ARITH_RULE `4 = 2 * 2`; GSYM REAL_POW_POW] THEN
      ASM_SIMP_TAC[POW_2_SQRT; REAL_POW_LE; REAL_ARITH `&1 <= tt ==> &0 <= tt`];
      MATCH_MP_TAC SQRT_MONO_LE THEN MATCH_MP_TAC SQRT_MONO_LE THEN
      ASM_REAL_ARITH_TAC];
    ALL_TAC] THEN
  SUBGOAL_THEN `&1 + log x <= &4 * q` ASSUME_TAC THENL
   [SUBGOAL_THEN `&0 < q` ASSUME_TAC THENL [ASM_REAL_ARITH_TAC; ALL_TAC] THEN
    SUBGOAL_THEN `log x = &4 * log q` SUBST1_TAC THENL
     [ASM_SIMP_TAC[LOG_POW]; ALL_TAC] THEN
    MP_TAC(SPEC `q - &1` LOG_LE) THEN
    REWRITE_TAC[REAL_ARITH `&1 + (q - &1) = q`] THEN ASM_REAL_ARITH_TAC;
    ALL_TAC] THEN
