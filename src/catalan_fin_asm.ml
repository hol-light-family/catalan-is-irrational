  MP_TAC(SPECL [`14`; `Cx(&693149 / &1000000)`] TAYLOR_CEXP) THEN
  REWRITE_TAC[RE_CX; GSYM CX_EXP; GSYM CX_POW; GSYM CX_DIV] THEN
  SIMP_TAC[VSUM_CX; FINITE_NUMSEG; GSYM CX_SUB; COMPLEX_NORM_CX] THEN
